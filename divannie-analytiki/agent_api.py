"""HTTP entry point for the existing workflow and local SQLite catalog."""
import os
import logging
from time import perf_counter
import sqlite3
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from core.llm_client import LLMClient
from core.local_db_tools import LocalDBTravelTools, DB_PATH
from core.state import AgentState, Slot, SlotStatus
from core.workflow import AgentWorkflow

DB = Path(os.getenv("AGENT_DATABASE_PATH", DB_PATH)).resolve()
app = FastAPI(title="О!дин запрос — Agent API")
app.add_middleware(
    CORSMiddleware,
    allow_origins=os.getenv("AGENT_CORS_ORIGINS", "http://localhost:8080,http://127.0.0.1:8080").split(","),
    allow_methods=["GET", "POST"], allow_headers=["Content-Type"],
)


class ChatRequest(BaseModel):
    text: str = Field(min_length=1, max_length=12000)
    preferences: dict
    selectedId: str | None = None
    slotContext: str | None = None


def check_database():
    # Read-only mode prevents silently creating an empty database at a wrong path.
    with sqlite3.connect(DB.as_uri() + "?mode=ro", uri=True) as db:
        if db.execute("PRAGMA quick_check").fetchone()[0] != "ok":
            raise RuntimeError("Database integrity check failed")
        tables = {row[0] for row in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        if not {"hotels", "transport", "weather"}.issubset(tables):
            raise RuntimeError("Required catalog tables missing")
        return {name: db.execute(f'SELECT count(*) FROM "{name}"').fetchone()[0]
                for name in ("hotels", "transport", "weather")}


@app.get("/api/health")
def health():
    try:
        return {"status": "ok", "database": "sqlite", "rows": check_database(),
                "model": os.getenv("OLLAMA_MODEL", "qwen2.5:7b-instruct")}
    except Exception:
        raise HTTPException(503, "Catalog database unavailable") from None


def ranked_bundle(b):
    h, t, transfer = b["hotel"], b["transport"], b["transfer"]
    costs = {"hotel": h.get("price_rub", 0), "transport": t.get("price_rub", 0),
             "transfer": transfer.get("price_rub", 0), "extras": 0}
    explanation = b.get("explanation", {})
    trip = {
        "id": b["bundle_id"], "country": b.get("country", ""), "city": b["destination"],
        "region": "", "destinationKeys": [b["destination"]], "airport": "",
        "image": "/images/coast.jpg", "title": b["destination"], "subtitle": "Каталог SQLite",
        "hotel": {"name": h["hotel_name"], "stars": h["stars"], "rating": str(h.get("rating", "")),
                  "description": h.get("location_note", ""), "amenities": [],
                  "meals": h.get("meal_plan", ""), "pets": h.get("pet_friendly", False),
                  "checkin": h.get("check_in_time", "14:00"), "checkinUntil": "", "checkout": ""},
        "purposes": [], "seasons": [], "warmSea": [], "heatedPool": False, "central": False,
        "visaForRU": "required" if b.get("visa_required") else "free", "visaNote": "",
        "costs": costs, "flightHours": str(t.get("duration_hours", "")),
        "transferMinutes": transfer.get("duration_minutes", 0), "stop": "",
        "arrival": t.get("arrival_time", ""), "outbound": t.get("departure_time", ""),
        "returnDeparture": "", "activities": [], "risk": explanation.get("risks", ""),
    }
    return {"trip": trip, "score": 0, "reasons": [explanation.get("why", "")],
            "compromises": [explanation.get("tradeoffs", "")], "costs": costs,
            "total": b["price_total"]}


@app.post("/api/v1/chat")
def chat(payload: ChatRequest):
    try:
        check_database()
    except Exception:
        raise HTTPException(503, "Catalog database unavailable") from None
    prefs = dict(payload.preferences)
    try:
        state = AgentState.model_validate(prefs.get("agentState") or {})
    except ValueError:
        raise HTTPException(422, "Invalid agent state") from None
    # Reflect explicit UI slot edits, including persisted sessions made before HTTP integration.
    mapping = {"origin": "origin", "when": "dates", "destination": "destination", "purpose": "vibe"}
    for ui, core in mapping.items():
        item = prefs.get("slots", {}).get(ui, {})
        if item.get("status") in ("YES", "Vague"):
            setattr(state.slots, core, Slot(value=item["value"], status=SlotStatus.YES
                    if item["status"] == "YES" else SlotStatus.VAGUE))
    started = perf_counter()
    llm = LLMClient(strict=True, fast=True)
    workflow = AgentWorkflow(tools=LocalDBTravelTools(db_path=str(DB)), llm_client=llm)
    try:
        state = workflow.process_user_message(payload.text, state, generate_details=False)
        parsed_at = perf_counter()
        # Always render text actually generated by Qwen, grounded in workflow/DB output.
        answer = llm._call_ollama_json(
            'Ты туристический агент. Ответь по-русски в 1–3 коротких предложениях, без рассуждений. '
            'Верни только JSON с полем message (строка). '
            'Используй только переданные данные. Если есть clarification_question, задай этот вопрос. '
            'Не утверждай, что совершил бронирование или отправил запрос. '
            'Каталог учебный, цены не являются живыми предложениями.',
            {"user_message": payload.text,
             "slots": llm._build_current_slots_context(state),
             "clarification_question": state.clarification_question,
             "conflict": state.conflict_reason,
             "post_booking": workflow.last_post_booking_result,
             "options": [{"destination": b["destination"], "total_rub": b["price_total"],
                          "hotel": b["hotel"]["hotel_name"],
                          "tradeoffs": b.get("explanation", {}).get("tradeoffs", "")}
                         for b in state.recommendations[:5]]},
            max_tokens=256,
        )
        message = answer.get("message")
        if not isinstance(message, str) or not message.strip():
            raise ValueError("Invalid model response")
    except Exception:
        # Do not leak provider responses, URLs with credentials, or user data in errors.
        raise HTTPException(502, "Agent processing failed; check Ollama availability and model") from None
    logging.getLogger("uvicorn.error").info(
        "Agent timings: extraction_and_search=%.2fs answer=%.2fs total=%.2fs",
        parsed_at - started, perf_counter() - parsed_at, perf_counter() - started,
    )
    prefs["agentState"] = state.model_dump(mode="json")
    for ui, core in mapping.items():
        slot = getattr(state.slots, core)
        prefs.setdefault("slots", {})[ui] = {"value": str(slot.value or ""),
            "status": "Vague" if slot.status == SlotStatus.VAGUE else slot.status.value}
    if isinstance(state.slots.budget.value, (int, float)):
        prefs["budget"] = state.slots.budget.value
    if isinstance(state.slots.stars.value, int):
        prefs["stars"] = state.slots.stars.value
    if isinstance(state.slots.pet_friendly.value, bool):
        prefs["pet"] = state.slots.pet_friendly.value
    return {"preferences": prefs, "message": message, "canSearch": not bool(state.clarification_question),
            "conflicts": [], "results": [ranked_bundle(b) for b in state.recommendations],
            "changes": list(mapping)}
