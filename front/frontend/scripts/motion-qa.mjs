import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true});
const report=[],errors=[];
await mkdir('test-results/motion',{recursive:true});
for(const width of [1440,1280,1024,390]) {
 const context=await browser.newContext({viewport:{width,height:900}});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:8080');await page.evaluate(()=>document.fonts.ready);
 await page.getByLabel('Опишите поездку').fill('12 июня 2027 из Москвы в Европу, хочу прогулки и архитектуру, 6 ночей, 1 взрослый, до 130 тысяч');
 await page.getByRole('button',{name:'Отправить сообщение',exact:true}).click();
 await expect(page.locator('.results-layer:not([data-exiting=true]) .journey-card')).toHaveCount(2);
 await expect(page.locator('.results-layer:not([data-exiting=true]) .compact-journey')).toHaveCount(3);
 await page.locator('.motion-card').first().evaluate(e=>Promise.all(e.getAnimations({subtree:true}).map(a=>a.finished.catch(()=>{}))));
 await page.locator('img').evaluateAll(imgs=>Promise.all(imgs.map(i=>i.decode().catch(()=>{}))));
 await page.screenshot({path:`test-results/motion/workspace-${width}.png`,animations:'disabled'});
 const dims=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));assert(dims.scroll<=width);
 const before=await page.evaluate(()=>JSON.parse(localStorage.getItem('odin-travel-session-v2')));
 const opener=page.locator('.compact-journey button').first();await opener.click();
 const drawer=page.locator('.modal-drawer');await expect(drawer).toBeVisible();
 await page.screenshot({path:`test-results/motion/details-${width}.png`,animations:'disabled'});
 const box=await drawer.boundingBox();assert(box.x>=0&&box.x+box.width<=width+1);
 assert(await drawer.evaluate(d=>d.contains(document.activeElement)));
 const after=await page.evaluate(()=>JSON.parse(localStorage.getItem('odin-travel-session-v2')));assert.deepEqual(after.preferences,before.preferences);
 await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).toHaveCount(0);await expect(opener).toBeFocused();
 await page.locator('.save-button').first().click();await expect(page.locator('.toast')).toContainText('Поездка сохранена');
 await page.getByRole('button',{name:'Закрыть уведомление'}).click();
 await page.getByLabel('Сортировать поездки').selectOption('price');await page.getByLabel('Сортировать поездки').selectOption('match');
 if(width===390)await page.locator('.mobile-tabs').getByRole('button',{name:'Чат',exact:false}).click();
 await page.getByLabel('Ваше сообщение').fill('Хочу дешевле');await page.getByRole('button',{name:'Отправить сообщение',exact:true}).click();
 await expect(page.locator('.agent-processing')).toBeVisible();assert(await page.locator('.journey-card').count()>0);
 await expect(page.locator('.agent-processing')).toHaveCount(0);
 await expect(page.locator('.results-layer')).toHaveCount(1);
 const replay=await page.locator('.message-user').first().evaluate(e=>e.getAnimations().filter(a=>a.playState==='running').length);assert.equal(replay,0);
 await page.emulateMedia({reducedMotion:'reduce'});
 if(width===390)await page.locator('.mobile-tabs').getByRole('button',{name:'Поездки',exact:false}).click();
 await page.locator('.journey-photo').first().click();await expect(page.getByRole('dialog')).toBeVisible();
 assert.equal(await page.getByRole('dialog').evaluate(e=>e.getAnimations().filter(a=>a.playState==='running').length),0);
 await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.locator('.compact-journey button').first().click();
 const city=await page.getByRole('dialog').locator('.modal-heading h2').innerText();
 await page.getByRole('dialog').getByRole('button',{name:'Выбрать поездку',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'Детали поездки',exact:true})).toBeVisible();
 await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).toHaveCount(0);
 assert(city.includes(await page.locator('.journey-card h2').first().innerText()));
 if(width===390)await page.locator('.mobile-tabs').getByRole('button',{name:'Чат',exact:false}).click();
 await page.getByLabel('Ваше сообщение').fill(('Проверяю старые сообщения.\n').repeat(20));
 await page.getByRole('button',{name:'Отправить сообщение',exact:true}).click();await expect(page.locator('.agent-processing')).toHaveCount(0);
 await page.locator('.chat-history').evaluate(e=>{e.scrollTop=0;e.dispatchEvent(new WheelEvent('wheel',{deltaY:-100,bubbles:true}));});
 await page.getByLabel('Ваше сообщение').fill('Паспорт РФ');await page.getByRole('button',{name:'Отправить сообщение',exact:true}).click();
 await expect(page.locator('.agent-processing')).toHaveCount(0);
 assert.equal(await page.locator('.chat-history').evaluate(e=>e.scrollTop),0);
 report.push({width,status:'passed'});await context.close();
}
assert.deepEqual(errors,[]);await writeFile('test-results/motion/checks.json',JSON.stringify({report,errors},null,2));await browser.close();console.log(JSON.stringify(report));
